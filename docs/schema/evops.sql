-- H2 本地文件数据库初始化脚本。
-- F1：户外广告点位与上刊底账（点位档案 / 按周档期 / 上刊单 / 对冲单 / 外部回执 / 逐单留底）

CREATE TABLE IF NOT EXISTS t_evops_schema_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_no VARCHAR(32) NOT NULL,
    description VARCHAR(255) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_evops_schema_version UNIQUE (version_no)
);

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('base-0', 'EVOPS 初始工作区');

-- 单据号全局序列（单号唯一、单调，H2 序列保证并发取号不重）
CREATE SEQUENCE IF NOT EXISTS seq_order_no START WITH 1 INCREMENT BY 1;

-- 点位档案：编号、尺寸、朝向、商圈，一样不能少；site_no 重复存不进去
CREATE TABLE IF NOT EXISTS t_site (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_no VARCHAR(64) NOT NULL,
    size_spec VARCHAR(64) NOT NULL,
    orientation VARCHAR(32) NOT NULL,
    business_district VARCHAR(128) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'LISTED',
    operator_name VARCHAR(64) NOT NULL,
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_site_no UNIQUE (site_no)
);

-- 上刊单（含对冲单）：画面挂在点位上；状态 HUNG 挂起 / TAKEN_DOWN 落架 / OFFSET 已对冲
-- biz_period 按发生日 occur_date 落库时固化，跨月单不随查询日漂移
CREATE TABLE IF NOT EXISTS t_posting_order (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no VARCHAR(40) NOT NULL,
    root_order_id BIGINT,
    offset_of_order_id BIGINT,
    order_kind VARCHAR(16) NOT NULL DEFAULT 'POSTING',
    site_id BIGINT NOT NULL,
    creative_name VARCHAR(128) NOT NULL,
    week_start DATE NOT NULL,
    week_end DATE NOT NULL,
    occur_date DATE NOT NULL,
    biz_period CHAR(7) NOT NULL,
    status VARCHAR(16) NOT NULL,
    version_no INT NOT NULL DEFAULT 1,
    offset_reason VARCHAR(255),
    operator_name VARCHAR(64) NOT NULL,
    closed_time TIMESTAMP,
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_posting_order_no UNIQUE (order_no)
);
CREATE INDEX IF NOT EXISTS idx_order_period ON t_posting_order (biz_period);
CREATE INDEX IF NOT EXISTS idx_order_site_week ON t_posting_order (site_id, week_start);
CREATE INDEX IF NOT EXISTS idx_order_root ON t_posting_order (root_order_id);

-- 按周档期占用：同一屏同一周只能挂一张画面；RELEASED 后该周可重新上刊
CREATE TABLE IF NOT EXISTS t_slot_booking (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id BIGINT NOT NULL,
    week_start DATE NOT NULL,
    week_end DATE NOT NULL,
    status VARCHAR(16) NOT NULL,
    order_id BIGINT NOT NULL,
    order_no VARCHAR(40) NOT NULL,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_slot_site_week UNIQUE (site_id, week_start)
);

-- 逐单事件留底（只追加，不改不删）：谁经手、哪天发生、当时单据快照全在这里，支撑版本选择与回退
CREATE TABLE IF NOT EXISTS t_order_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    order_no VARCHAR(40) NOT NULL,
    root_order_id BIGINT NOT NULL,
    event_type VARCHAR(24) NOT NULL,
    version_no INT NOT NULL,
    occur_date DATE NOT NULL,
    operator_name VARCHAR(64) NOT NULL,
    related_order_no VARCHAR(40),
    detail VARCHAR(500),
    snapshot CLOB,
    event_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_event_order ON t_order_event (order_id, version_no);
CREATE INDEX IF NOT EXISTS idx_event_root ON t_order_event (root_order_id);

-- 外部回执：挂回原单据；即便回执指向对冲单，也回溯到根单
CREATE TABLE IF NOT EXISTS t_order_receipt (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_no VARCHAR(64) NOT NULL,
    order_id BIGINT NOT NULL,
    order_no VARCHAR(40) NOT NULL,
    root_order_id BIGINT NOT NULL,
    root_order_no VARCHAR(40),
    source VARCHAR(64),
    content VARCHAR(1000),
    occur_date DATE,
    operator_name VARCHAR(64) NOT NULL,
    received_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_receipt_no UNIQUE (receipt_no)
);
CREATE INDEX IF NOT EXISTS idx_receipt_root ON t_order_receipt (root_order_id);
CREATE INDEX IF NOT EXISTS idx_receipt_order ON t_order_receipt (order_id);

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('f1-ledger-1', '户外广告点位与上刊底账：点位档案、按周档期、上刊/落架/对冲单、外部回执、逐单事件留底');
